def main() -> None:
    parser = argparse.ArgumentParser(description="Generate StreamPlay v4.4 Xcode project")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument("--force", action="store_true", help="Overwrite existing generated files")
    args = parser.parse_args()
    root = args.output.resolve()
    root.mkdir(parents=True, exist_ok=True)
    copied = preserved = 0
    data = zlib.decompress(base64.b85decode(BUNDLE.encode("ascii")))
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:") as archive:
        for member in archive.getmembers():
            if not member.isfile():
                continue
            dest = (root / member.name).resolve()
            if not dest.is_relative_to(root):
                raise ValueError("Unsafe archive path")
            dest.parent.mkdir(parents=True, exist_ok=True)
            if dest.exists() and not args.force:
                preserved += 1
                continue
            contents = archive.extractfile(member).read()
            dest.write_bytes(contents)
            if member.name.startswith("scripts/"):
                dest.chmod(0o755)
            copied += 1
    # Keeping the generator beside its generated project makes the copy usable independently.
    own = root / "gen_xcodeproj.py"
    if not own.exists() or args.force:
        if own.resolve() != Path(__file__).resolve():
            own.write_bytes(Path(__file__).read_bytes())
            own.chmod(0o755)
            copied += 1
    print(f"StreamPlay v4.4: {root}")
    print(f"Generated: {copied} | Preserved: {preserved}")
    print("Open StreamPlay.xcodeproj with Xcode 27+ or use GitHub Actions.")
    print("CarPlay video/window requires Apple-approved entitlements; sideloading alone cannot grant them.")

if __name__ == "__main__":
    main()
